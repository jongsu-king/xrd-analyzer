EXIT_INPUT = 2
EXIT_ANALYSIS = 3

AXIS_CHOICES = {
    "2theta-deg": ("2theta", "deg"),
    "2theta-rad": ("2theta", "rad"),
    "theta-deg": ("theta", "deg"),
    "theta-rad": ("theta", "rad"),
}


def write_example_files(out_dir: str | Path) -> list[Path]:
    """Write every synthetic example as CSV plus a ground-truth JSON and its recipe."""
    d = Path(out_dir)
    d.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for key in EXAMPLES:
        ex = make_example(key)
        p = d / f"synthetic_{key}.csv"
        with p.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write("# SYNTHETIC EXAMPLE generated by xrd-analyzer - NOT instrument data\n")
            fh.write("# synthetic: yes\n")
            fh.write(f"# example: {key}\n")
            fh.write(f"# description: {ex.description}\n")
            fh.write(f"# generator_wavelength_A: {ex.truth['wavelength_A']}\n")
            fh.write("two_theta_deg,intensity_counts\n")
            for xv, yv in zip(ex.pattern.two_theta_deg, ex.pattern.intensity, strict=True):
                fh.write(f"{xv:.4f},{int(yv)}\n")
        truth = d / f"synthetic_{key}_truth.json"
        truth.write_text(json.dumps(ex.truth, indent=2, ensure_ascii=False), encoding="utf-8")
        recipe = d / f"synthetic_{key}_recipe.json"
        ex.recipe.save(recipe)
        written += [p, truth, recipe]
    return written


def _parse_wavelength(text: str) -> float:
    try:
        return preset(text).wavelength_A
    except KeyError:
        pass
    try:
        return float(text)
    except ValueError:
        keys = ", ".join(p.key for p in WAVELENGTH_PRESETS)
        raise argparse.ArgumentTypeError(
            f"wavelength must be a number in Å or one of: {keys}"
        ) from None


def _recipe_from_args(a: argparse.Namespace) -> AnalysisRecipe:
    r = AnalysisRecipe.load(a.recipe) if a.recipe else AnalysisRecipe()
    pp, sz = r.preprocess, r.size
    if a.wavelength is not None:
        pp.wavelength_A = a.wavelength
    if a.ka2 is not None:
        pp.kalpha2_mode = a.ka2
        if a.ka2 != "none" and pp.wavelength2_A is None:
            pp.wavelength2_A = a.wavelength2
    if a.wavelength2 is not None:
        pp.wavelength2_A = a.wavelength2
    if a.baseline is not None:
        pp.baseline_method = a.baseline
    if a.duplicates is not None:
        pp.duplicate_policy = a.duplicates
    if a.profile is not None:
        r.fit.profile = a.profile
    if a.K is not None:
        sz.scherrer_K = a.K
    if a.inst_fwhm is not None:
        sz.instrument_mode = "constant"
        sz.instrument_fwhm_deg = a.inst_fwhm
    if a.add_peak:
        r.peaks.manual_add_deg = list(r.peaks.manual_add_deg) + a.add_peak
    if a.remove_peak:
        r.peaks.manual_remove_deg = list(r.peaks.manual_remove_deg) + a.remove_peak
    return r


def _read_options(a: argparse.Namespace) -> ReadOptions:
    q, u = AXIS_CHOICES[a.axis] if a.axis else (None, None)
    return ReadOptions(
        x_column=a.x_col,
        y_column=a.y_col,
        axis_quantity=q,
        axis_unit=u,
        intensity_unit=a.intensity_unit,
        drop_nonfinite=a.drop_nonfinite,
    )


def _references(a: argparse.Namespace, wavelength: float | None) -> list[ReferencePattern]:
    refs: list[ReferencePattern] = []
    for path in a.reference_csv or []:
        refs.append(load_reference_csv(path))
    for spec in a.reference_cubic or []:
        parts = spec.split(",")
        if len(parts) not in (2, 3):
            raise ValueError("--reference-cubic expects a_A,centering[,name]")
        name = parts[2] if len(parts) == 3 else f"cubic {parts[1]} a={parts[0]}"
        refs.append(reference_from_cubic(name, float(parts[0]), parts[1], wavelength or 1.54))
    return refs


def _add_analysis_args(p: argparse.ArgumentParser) -> None:
    p.add_argument("--recipe", help="recipe JSON (CLI options override it)")
    p.add_argument(
        "--wavelength",
        type=_parse_wavelength,
        help="X-ray wavelength in Å or preset key (cu_ka1, cu_ka_avg)",
    )
    p.add_argument("--wavelength2", type=float, help="Kα2 wavelength in Å")
    p.add_argument("--ka2", choices=["none", "strip", "fit_doublet"])
    p.add_argument(
        "--axis",
        choices=sorted(AXIS_CHOICES),
        help="confirm the x column quantity/unit (required unless the header says)",
    )
    p.add_argument("--x-col", type=int)
    p.add_argument("--y-col", type=int)
    p.add_argument("--intensity-unit", help="counts | cps | a.u.")
    p.add_argument("--drop-nonfinite", action="store_true")
    p.add_argument("--duplicates", choices=["error", "average", "keep_first"])
    p.add_argument("--baseline", choices=["none", "snip", "als", "poly", "masked"])
    p.add_argument("--profile", choices=["pseudo_voigt", "voigt"])
    p.add_argument("--K", type=float, help="Scherrer shape factor")
    p.add_argument("--inst-fwhm", type=float, help="constant instrumental FWHM (deg 2θ)")
    p.add_argument("--add-peak", type=float, action="append", help="manual peak at 2θ (deg)")
    p.add_argument("--remove-peak", type=float, action="append", help="remove peak near 2θ")
    p.add_argument("--reference-csv", action="append", help="licensed reference CSV")
    p.add_argument(
        "--reference-cubic",
        action="append",
        help="computed cubic reference: a_A,centering[,name] (P, I, F, diamond)",
    )
    p.add_argument("--out", required=True, help="output directory")
    p.add_argument("--no-pdf", action="store_true")


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="xrd-analyzer", description=f"XRD Analyzer {__version__}. {DISCLAIMER_EN}"
    )
    ap.add_argument("--version", action="version", version=__version__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("formats", help="list file formats and their verification status")
    pe = sub.add_parser("examples", help="write synthetic example files")
    pe.add_argument("--out", required=True)
    pa = sub.add_parser("analyze", help="analyse one file")
    pa.add_argument("file")
    _add_analysis_args(pa)
    pb = sub.add_parser("batch", help="analyse several files with one recipe")
    pb.add_argument("files", nargs="+")
    _add_analysis_args(pb)
    sub.add_parser("gui", help="start the desktop GUI")
    ps = sub.add_parser("selftest", help="verify this installation against synthetic ground truth")
    ps.add_argument("--out", help="also write the JSON report to this file")
    pu = sub.add_parser(
        "update", help="check GitHub for a newer release and install it (installed copies)"
    )
    pu.add_argument(
        "--check-only", action="store_true", help="only report whether a newer release exists"
    )
    pg = sub.add_parser("gui-smoke", help="open the GUI, analyse an example, close (build check)")
    pg.add_argument("--out", help="also write the JSON report to this file")
    pg.add_argument("--offscreen", action="store_true", help="no display needed")
    return ap


def main(argv: Sequence[str] | None = None) -> int:
    a = build_parser().parse_args(argv)
    if a.cmd == "formats":
        for f in list_formats():
            print(f"{', '.join(f['extensions']):<28} {f['status']:<16} {f['description']}")
        return 0
    if a.cmd == "examples":
        for p in write_example_files(a.out):
            print(p)
        return 0
    if a.cmd == "selftest":
        from .selftest import run_selftest, write_report

        report = run_selftest()
        write_report(report, a.out)
        return 0 if report["ok"] else 1
    if a.cmd == "gui-smoke":
        from .selftest import run_gui_smoke, write_report

        report = run_gui_smoke(offscreen=a.offscreen)
        write_report(report, a.out)
        return 0 if report["ok"] else 1
    if a.cmd == "update":
        from . import selfupdate

        updater = selfupdate.Updater(
            selfupdate.App(
                repo="jongsu-king/xrd-analyzer",
                name="XRD Analyzer",
                version=__version__,
                env_prefix="XRD_ANALYZER",
                pip_name="xrd-analyzer",
            )
        )
        return selfupdate.cli(updater, install=not a.check_only)
    if a.cmd == "gui":
        from .ui.app import main as gui_main

        return gui_main()
    try:
        recipe = _recipe_from_args(a)
        refs = _references(a, recipe.preprocess.wavelength_A)
        opts = _read_options(a)
    except (ValueError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_INPUT
    out = Path(a.out)
    files = [a.file] if a.cmd == "analyze" else a.files
    patterns = []
    failed = 0
    for f in files:
        try:
            patterns.append(read_pattern(f, opts))
        except (XRDFormatError, OSError) as exc:
            print(f"error: {exc}", file=sys.stderr)
            failed += 1
    if not patterns:
        return EXIT_INPUT
    try:
        if a.cmd == "analyze":
            res = run_analysis(patterns[0], recipe, references=refs)
            for p in export_all(res, out, pdf=not a.no_pdf):
                print(p)
            for w in res.warnings:
                print(f"warning: {w}", file=sys.stderr)
            return 0
        items = run_batch(
            patterns,
            recipe,
            references=refs,
            progress=lambda f, m: print(f"[{f:4.0%}] {m}", file=sys.stderr),
        )
    except (AnalysisError, AnalysisCancelled) as exc:
        print(f"analysis error: {exc}", file=sys.stderr)
        return EXIT_ANALYSIS
    out.mkdir(parents=True, exist_ok=True)
    summary: list[dict[str, Any]] = []
    for it in items:
        if it.result is None:
            failed += 1
            print(f"FAILED {it.name}: {it.error}", file=sys.stderr)
            summary.append({"name": it.name, "error": it.error})
            continue
        write_peak_table_csv(it.result, out / f"{it.name}_peaks.csv")
        export_all(it.result, out / it.name, pdf=not a.no_pdf)
        centers = [p.center_deg for p in it.result.fit.peaks if p.ok]
        summary.append(
            {
                "name": it.name,
                "n_peaks": len(centers),
                "peaks_two_theta_deg": [round(float(c), 5) for c in np.sort(centers)],
            }
        )
    (out / "batch_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(out / "batch_summary.json")
    return EXIT_ANALYSIS if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
