"""Deterministic SYNTHETIC example patterns with known ground truth.

These are generated by this program and are NOT instrument data. Peak heights are
arbitrary illustrative values (no structure-factor calculation). Each example carries the
exact parameters used, so tests can check the analysis against the truth.
"""

from __future__ import annotations

import math
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from ..models.dataset import SYNTHETIC_ONLY, XRDPattern
from ..models.recipe import AnalysisRecipe
from ..models.units import CU_KA1_A, CU_KA2_A, SI_LATTICE_A
from . import profiles
from .crystallography import cubic_reflections

SI_HEIGHTS = {3: 10000.0, 8: 6000.0, 11: 3500.0, 16: 900.0, 19: 1300.0, 24: 1700.0}
SI_CAGLIOTI = (0.004, -0.002, 0.004)  # U, V, W in deg² (synthetic instrument)
FCC_A = 4.0786  # "fcc-like" lattice used only for the synthetic nanocrystalline example
FCC_HEIGHTS = {3: 5000.0, 4: 2400.0, 8: 1500.0, 11: 1600.0, 12: 450.0, 16: 250.0}


@dataclass
class SyntheticExample:
    key: str
    title: str
    description: str
    pattern: XRDPattern
    truth: dict[str, Any]
    recipe: AnalysisRecipe = field(default_factory=AnalysisRecipe)


def _caglioti(two_theta: float, u: float, v: float, w: float) -> float:
    t = math.tan(math.radians(two_theta) / 2)
    return math.sqrt(u * t * t + v * t + w)


def si_like(seed: int = 11, include_ka2: bool = False) -> SyntheticExample:
    x = np.round(np.arange(20.0, 90.0 + 1e-9, 0.01), 6)
    eta = 0.5
    bg = 200.0 + 300.0 * np.exp(-(x - 20.0) / 15.0)
    y = bg.copy()
    peaks = []
    for r in cubic_reflections(SI_LATTICE_A, "diamond", CU_KA1_A, 20.0, 90.0):
        h = SI_HEIGHTS[r.n_sq]
        w = _caglioti(r.two_theta_deg, *SI_CAGLIOTI)
        y += profiles.pseudo_voigt(x, r.two_theta_deg, h, w, eta)
        if include_ka2:
            c2 = profiles.kalpha2_position(r.two_theta_deg, CU_KA1_A, CU_KA2_A)
            y += profiles.pseudo_voigt(x, c2, 0.5 * h, w, eta)
        peaks.append(
            {
                "hkl": r.hkl,
                "two_theta_deg": r.two_theta_deg,
                "d_A": r.d_A,
                "fwhm_deg": w,
                "height": h,
                "eta": eta,
            }
        )
    counts = np.random.default_rng(seed).poisson(y).astype(float)
    key = "si_like_ka2" if include_ka2 else "si_like"
    title = "Synthetic Si-like (Cu Kα1+Kα2)" if include_ka2 else "Synthetic Si-like (Cu Kα1)"
    pat = XRDPattern(
        name=f"SYNTHETIC_{key}",
        two_theta_deg=x,
        intensity=counts,
        intensity_unit="counts",
        metadata={
            "synthetic": "yes — generated by xrd_analyzer.core.synthetic",
            "seed": str(seed),
        },
        parser="synthetic-generator",
        format_status=SYNTHETIC_ONLY,
        synthetic=True,
    )
    truth = {
        "wavelength_A": CU_KA1_A,
        "lattice_A": SI_LATTICE_A,
        "centering": "diamond",
        "caglioti_UVW": SI_CAGLIOTI,
        "ka2": include_ka2,
        "ka2_ratio": 0.5,
        "wavelength2_A": CU_KA2_A,
        "peaks": peaks,
    }
    recipe = AnalysisRecipe()
    recipe.preprocess.wavelength_A = CU_KA1_A
    recipe.preprocess.snip_iterations = 60
    if include_ka2:
        recipe.preprocess.kalpha2_mode = "fit_doublet"
        recipe.preprocess.wavelength2_A = CU_KA2_A
        recipe.preprocess.ka2_ratio = 0.5
    desc = (
        "Diamond-cubic Si-like pattern, a = 5.431020511 Å, pseudo-Voigt (η=0.5) with "
        "Caglioti widths, Poisson noise. Heights are arbitrary. Instrumental broadening "
        "is left unset in the recipe so Scherrer correctly reports 'not computable'."
    )
    return SyntheticExample(key, title, desc, pat, truth, recipe)


def nanocrystalline(
    seed: int = 13,
    D_nm: float = 15.0,
    strain: float = 0.0015,
    K: float = 0.9,
    inst_fwhm_deg: float = 0.08,
) -> SyntheticExample:
    x = np.round(np.arange(20.0, 106.0 + 1e-9, 0.02), 6)
    eta = 0.3
    amorphous = 800.0 * np.exp(-4 * math.log(2) * ((x - 24.0) / 8.0) ** 2)
    bg = 150.0 + amorphous
    y = bg.copy()
    peaks = []
    for r in cubic_reflections(FCC_A, "F", CU_KA1_A, 20.0, 106.0):
        th = math.radians(r.two_theta_deg) / 2
        beta_s = K * CU_KA1_A / (D_nm * 10.0 * math.cos(th)) + 4 * strain * math.tan(th)
        beta_s_deg = math.degrees(beta_s)
        beta_m = math.hypot(beta_s_deg, inst_fwhm_deg)
        h = FCC_HEIGHTS[r.n_sq]
        y += profiles.pseudo_voigt(x, r.two_theta_deg, h, beta_m, eta)
        peaks.append(
            {
                "hkl": r.hkl,
                "two_theta_deg": r.two_theta_deg,
                "d_A": r.d_A,
                "fwhm_deg": beta_m,
                "sample_fwhm_deg": beta_s_deg,
                "height": h,
                "eta": eta,
            }
        )
    counts = np.random.default_rng(seed).poisson(y).astype(float)
    pat = XRDPattern(
        name="SYNTHETIC_nano_fcc",
        two_theta_deg=x,
        intensity=counts,
        intensity_unit="counts",
        metadata={
            "synthetic": "yes — generated by xrd_analyzer.core.synthetic",
            "seed": str(seed),
        },
        parser="synthetic-generator",
        format_status=SYNTHETIC_ONLY,
        synthetic=True,
    )
    truth = {
        "wavelength_A": CU_KA1_A,
        "lattice_A": FCC_A,
        "centering": "F",
        "D_nm": D_nm,
        "strain": strain,
        "K": K,
        "instrument_fwhm_deg": inst_fwhm_deg,
        "amorphous_center_deg": 24.0,
        "peaks": peaks,
    }
    recipe = AnalysisRecipe()
    recipe.preprocess.wavelength_A = CU_KA1_A
    recipe.preprocess.snip_iterations = 150  # provisional pass for the peak mask
    recipe.preprocess.baseline_method = "masked"  # keeps the amorphous hump in the baseline
    recipe.peaks.min_distance_deg = 0.5
    recipe.peaks.prominence_sigma = 10.0
    recipe.peaks.min_width_deg = 0.2
    recipe.peaks.max_width_deg = 3.0
    recipe.size.scherrer_K = K
    recipe.size.instrument_mode = "constant"
    recipe.size.instrument_fwhm_deg = inst_fwhm_deg
    desc = (
        f"fcc-like nanocrystalline pattern (a = {FCC_A} Å, not a real sample) with "
        f"D = {D_nm} nm, ε = {strain}, K = {K}, instrumental FWHM {inst_fwhm_deg}° "
        "(quadratic combination), amorphous hump at 24°, Poisson noise."
    )
    return SyntheticExample(
        "nano_fcc", "Synthetic nanocrystalline fcc-like + amorphous hump", desc, pat, truth, recipe
    )


EXAMPLES: dict[str, Callable[[], SyntheticExample]] = {
    "si_like": lambda: si_like(),
    "si_like_ka2": lambda: si_like(seed=12, include_ka2=True),
    "nano_fcc": lambda: nanocrystalline(),
}


def make_example(key: str) -> SyntheticExample:
    try:
        return EXAMPLES[key]()
    except KeyError:
        raise KeyError(f"unknown example {key!r}; available: {sorted(EXAMPLES)}") from None
